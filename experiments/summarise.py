#!/usr/bin/env python3
"""
Collect the recorded experiment results into experiments/results/SUMMARY.md.

    python experiments/summarise.py

Reads only experiments/results/*/status.json and results.json (nothing is recomputed). The control table
lists, per scenario and controller, the mean over seeds of: total energy, savings vs the conventional
schedule (negative = more energy), share of occupied time with |PMV| > 0.5, PMV-hours above 0.5,
IAQ minutes above 1000 ppm, AC on/off cycles and fail-safe fall-backs.
"""
from __future__ import annotations

import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "experiments", "results")
ORDER = ["schedule", "always_on", "threshold_rf", "mo", "ppo"]
NAMES = {"schedule": "Conventional schedule", "always_on": "Always on", "threshold_rf": "RF threshold rule",
         "mo": "Multi-objective (MPC-like)", "ppo": "PPO"}


def control_rows():
    rows = []
    for exp in ("exp01_baseline", "exp05_control", "exp06_occupancy_variation", "exp07_weather", "exp08_fault_tolerance"):
        p = os.path.join(RES, exp, "results.json")
        if not os.path.exists(p):
            continue
        with open(p, encoding="utf-8") as f:
            r = json.load(f)
        for sc, by in r["summary"].items():
            for c in ORDER:
                m = by.get(c)
                if not m or m.get("status") == "error":
                    continue
                rows.append({"experiment": exp, "scenario": sc, "controller": c, **m})
    return rows


def table(rows, scenario_filter=None) -> str:
    out = ["| experiment | scenario | controller | energy kWh (7 d) | savings vs schedule | discomfort (share of occupied time) | "
           "PMV-hours > 0.5 | IAQ room-min > 1000 ppm | AC on/off cycles | fail-safe F1 / F2 / F3 |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if scenario_filter and r["scenario"] not in scenario_filter:
            continue
        out.append(f"| {r['experiment'][:5]} | {r['scenario']} | {NAMES.get(r['controller'], r['controller'])} | "
                   f"{r['energy_kwh']:.0f} ± {r['energy_kwh_sd']:.0f} | {r['savings_vs_schedule_pct']:+.1f} % | "
                   f"{100 * r['discomfort_share']:.1f} % | {r['discomfort_pmv_h']:.1f} | {r['iaq_min']:.0f} | "
                   f"{r['ac_cycles']:.0f} | {r['failsafe_F1']:.0f} / {r['failsafe_F2']:.0f} / {r['failsafe_F3']:.0f} |")
    return "\n".join(out)


def main() -> int:
    lines = ["# Experiment summary", "", "Generated by `python experiments/summarise.py` from the recorded results "
             "(nothing recomputed). Control results are synthetic (digital twin): 7 measured days, seeds 1-3, "
             "matched weather, occupants, sensor noise and faults; mean ± sd over seeds. A control run is reused from "
             "`experiments/results/run_cache/` only when the simulator and controller code, the policy file and the "
             "model version it depends on are byte-identical (`rl/evaluate.py`).", "",
             "## Status", "", "| experiment | status | finished | wall time |", "|---|---|---|---|"]
    for p in sorted(glob.glob(os.path.join(RES, "exp*", "status.json"))):
        with open(p, encoding="utf-8") as f:
            s = json.load(f)
        info = s.get("info") or {}
        wall = f"{s['wall_s']:.0f} s"
        if info.get("runs_from_cache"):
            wall += (f" ({info['runs_from_cache']} of {info['runs']} runs reused from the run cache; "
                     f"simulation time of the runs {info['simulation_s']:.0f} s)")
        lines.append(f"| {s['id']} - {s['title']} | **{s['status']}** | {s['finished']} | {wall} |")
    rows = control_rows()
    if rows:
        lines += ["", "## Control", "", table(rows)]
    for exp, title in (("exp05_control", "PPO training-seed variability and confirmation on new evaluation seeds"),
                       ("exp08_fault_tolerance", "Additional failure cases")):
        p = os.path.join(RES, exp, "extra.json")
        if os.path.exists(p):
            with open(p, encoding="utf-8") as f:
                extra = json.load(f)
            lines += ["", f"## {title}", ""] + [f"- **{k}**: {v.get('result')}" for k, v in extra.items()]
    for exp in ("exp09_consistency", "exp10_live_room", "exp11_real_room_replay"):
        p = os.path.join(RES, exp, "summary.md")
        if os.path.exists(p):
            with open(p, encoding="utf-8") as f:
                body = f.read().split("\n", 1)[1]
            lines += ["", f"## {exp}", body.strip()]
    with open(os.path.join(RES, "SUMMARY.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())

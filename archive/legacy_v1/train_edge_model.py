import pandas as pd
import numpy as np
import joblib
from sklearn.tree import DecisionTreeClassifier
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import Pipeline
from micromlgen import port
from pathlib import Path

def train_and_export_edge_model():
    print("Loading dataset...")
    # Using the Kaggle dataset
    data_path = Path("Dataset/Kaggle_Room_Occupancy/datatraining.txt")
    if not data_path.exists():
        print(f"Error: Could not find dataset at {data_path}")
        return

    df = pd.read_csv(data_path, parse_dates=['date'])
    df.set_index('date', inplace=True)

    
    # Same features as the big model
    features = ['Temperature', 'Humidity', 'Light', 'CO2', 'HumidityRatio']
    target = 'Occupancy'
    
    X = df[features]
    y = df[target]
    
    print("Training ultra-lightweight Edge AI Model (Decision Tree, depth=4)...")
    
    # We use a standard scaler and imputer, but we'll export them manually to C++
    imputer = SimpleImputer(strategy='median')
    scaler = StandardScaler()
    
    X_imputed = imputer.fit_transform(X)
    X_scaled = scaler.fit_transform(X_imputed)
    
    # Train the Decision Tree
    clf = DecisionTreeClassifier(max_depth=4, random_state=42)
    clf.fit(X_scaled, y)
    
    accuracy = clf.score(X_scaled, y)
    print(f"Edge Model Accuracy on Training Data: {accuracy:.4f}")
    
    print("Exporting model to C++ header using micromlgen...")
    cpp_code = port(clf)
    
    means = scaler.mean_
    scales = scaler.scale_

    scaler_cpp = f"""
// Auto-generated Scaler Code for Edge AI
float scaler_mean[] = {{{', '.join(map(str, means))}}};
float scaler_scale[] = {{{', '.join(map(str, scales))}}};

void apply_scaler(float* features, int length) {{
    for (int i = 0; i < length; i++) {{
        features[i] = (features[i] - scaler_mean[i]) / scaler_scale[i];
    }}
}}
"""
    
    output_dir = Path("firmware/esp32_smart_building")
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / "model_inference.h"
    
    with open(output_path, "w") as f:
        f.write("#pragma once\n\n")
        f.write("// Lightweight Edge AI Model for ESP32\n")
        f.write("// Generated by train_edge_model.py\n\n")
        f.write(scaler_cpp)
        f.write("\n")
        f.write(cpp_code)

    print(f"Successfully exported Edge Model to {output_path}")

if __name__ == "__main__":
    train_and_export_edge_model()
